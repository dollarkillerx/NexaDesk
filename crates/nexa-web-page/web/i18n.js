function pick() {
  for (const tag of navigator.languages || [navigator.language || "en"]) {
    const l = tag.toLowerCase();
    if (l.startsWith("zh")) return "zh-Hans";
    if (l.startsWith("ja")) return "ja";
    if (l.startsWith("en")) return "en";
  }
  return "en";
}

const LANG_KEY = "nexadesk.lang";

/** The languages the page speaks, as [code, name in that language]. */
export const LANGS = [["zh-Hans", "中文"], ["en", "English"], ["ja", "日本語"]];

function saved() {
  try {
    const l = localStorage.getItem(LANG_KEY);
    return l && STRINGS[l] ? l : null;
  } catch {
    return null;
  }
}

/** The language in use: the one picked on the page before, else the browser's. */
export let lang = saved() ?? pick();

/** Switches the page to `l` and remembers it in this browser. */
export function setLang(l) {
  if (!STRINGS[l]) return;
  lang = l;
  try { localStorage.setItem(LANG_KEY, l); } catch {}
  apply();
}

export function t(key) {
  return STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
}

/** Fills every element carrying data-t="key". */
export function apply(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll("[data-t]")) el.textContent = t(el.dataset.t);
}
